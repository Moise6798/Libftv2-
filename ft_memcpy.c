#include <stddef.h>

void	*ft_memcpy(void *dest, const void *src, size_t n)
{
	unsigned char	*d;
	unsigned char	*s;

	d = (unsigned char *)dest;
	s = (unsigned char *)src;
	if (!d && !s)
		return (0);
	if ((d == s) || (n == 0))
		return (dest);
	while (n)
	{
		d[n] = s[n];
		n--;
	}
	return (d);
}
